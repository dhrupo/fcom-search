CREATE TABLE IF NOT EXISTS cities (
  id INTEGER PRIMARY KEY, name TEXT NOT NULL, ascii TEXT NOT NULL, name_key TEXT NOT NULL, ascii_key TEXT NOT NULL,
  country TEXT NOT NULL, lat REAL NOT NULL, lon REAL NOT NULL, population INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS cities_big_lat ON cities (lat) WHERE population >= 100000;
CREATE INDEX IF NOT EXISTS cities_name_key ON cities (name_key);
CREATE INDEX IF NOT EXISTS cities_ascii_key ON cities (ascii_key);
CREATE TABLE IF NOT EXISTS countries (code TEXT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (name TEXT PRIMARY KEY, data TEXT NOT NULL, at REAL NOT NULL);
CREATE TABLE IF NOT EXISTS photon_cache (key TEXT PRIMARY KEY, body TEXT NOT NULL, at REAL NOT NULL);
CREATE INDEX IF NOT EXISTS photon_cache_at ON photon_cache (at);
CREATE TABLE IF NOT EXISTS slugs (key TEXT PRIMARY KEY, works INTEGER NOT NULL, checked_at REAL NOT NULL);
CREATE TABLE IF NOT EXISTS pools (pool_key TEXT PRIMARY KEY, data TEXT NOT NULL, fetched_at REAL NOT NULL);
CREATE INDEX IF NOT EXISTS pools_age ON pools (fetched_at);
CREATE TABLE IF NOT EXISTS fetches (key TEXT PRIMARY KEY, at REAL NOT NULL);
CREATE INDEX IF NOT EXISTS fetches_at ON fetches (at);
CREATE TABLE IF NOT EXISTS searches (id TEXT PRIMARY KEY, state TEXT NOT NULL, version INTEGER NOT NULL DEFAULT 0, at REAL NOT NULL);
CREATE INDEX IF NOT EXISTS searches_at ON searches (at);
CREATE TABLE IF NOT EXISTS private_names (name TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS ai_budget (day INTEGER PRIMARY KEY, used INTEGER NOT NULL);
